import Foundation

// MARK: - SDKAssistTypes
//
// Public value types for the host-side Assist SDK variants
// (Docs/Intro-to-SDK.md §11 — task B2):
//
//   - `assistSDK.UI` — the host presents the REAL `AssistMainView` for the
//     agreed viewId (`SDKAssistUIOpener.assistMainViewID`, `"assist.main"`).
//     The extension never touches Assist internals; there is no custom
//     Assist chrome.
//   - `assistSDK` (headless) — `SDKAssistService` owns session lifecycle,
//     streaming responses, and tool access per approved scope. Every call
//     is entitlement-gated before any host state is touched.
//
// All types are plain `Sendable` values. Nothing here is a mock: these are
// the shapes the real service produces and consumes. Where the real Assist
// backend cannot yet be reached without new caller-identity plumbing, the
// service throws a typed error (see `SDKAssistService`) — it never
// fabricates a response.

// MARK: - Message

/// One turn in an Assist SDK session's history.
public struct SDKAssistMessage: Sendable, Codable {
    /// Who produced the turn.
    public enum Role: String, Sendable, Codable {
        case user
        case assistant
    }

    public let role: Role
    public let content: String
    public let timestamp: Date

    public init(role: Role, content: String, timestamp: Date = Date()) {
        self.role = role
        self.content = content
        self.timestamp = timestamp
    }
}

// MARK: - Session options

/// Options accepted by `SDKAssistService.createSession`. Kept minimal and
/// real: every field is validated, bounded, and stored on the session
/// record. There are no behavior flags the backend does not implement.
public struct SDKAssistSessionOptions: Sendable {
    /// Optional human-readable label for the session (e.g. shown in host
    /// diagnostics). Bounded to 256 characters; empty becomes nil.
    public let title: String?
    /// Optional system prompt for the session, stored verbatim on the
    /// session record (bounded to 16 KiB; empty becomes nil). Accepted
    /// because the `assist.invoke` wire contract sends it
    /// (`TypeScript/package/src/assist.ts`); until the per-extension
    /// backend lands it is recorded, not applied — the service never
    /// claims otherwise.
    public let systemPrompt: String?
    /// Optional model identifier requested for the session, stored
    /// verbatim (bounded to 256 characters; empty becomes nil). Same
    /// honesty contract as `systemPrompt`.
    public let model: String?

    public init(title: String? = nil, systemPrompt: String? = nil, model: String? = nil) {
        if let title, !title.isEmpty {
            self.title = String(title.prefix(256))
        } else {
            self.title = nil
        }
        if let systemPrompt, !systemPrompt.isEmpty {
            self.systemPrompt = String(systemPrompt.prefix(16 * 1024))
        } else {
            self.systemPrompt = nil
        }
        if let model, !model.isEmpty {
            self.model = String(model.prefix(256))
        } else {
            self.model = nil
        }
    }
}

// MARK: - Session snapshot

/// An immutable snapshot of one headless Assist session owned by
/// `SDKAssistService`. Sessions are host-owned records: `id` is the only
/// handle the extension ever sees, and every mutating call re-verifies
/// that the caller owns the session's `extensionID`.
public struct SDKAssistSession: Sendable {
    /// The session handle. Generated by the host; never caller-supplied.
    public let id: UUID
    /// The extension that owns this session. Calls from any other
    /// extension ID are denied with `.permissionDenied`.
    public let extensionID: String
    public let title: String?
    /// System prompt stored verbatim from the create options (see
    /// `SDKAssistSessionOptions`).
    public let systemPrompt: String?
    /// Model identifier stored verbatim from the create options.
    public let model: String?
    public let createdAt: Date
    /// True after `closeSession`; closed sessions reject new work.
    public let isClosed: Bool
    /// Conversation history recorded by the service. Assistant turns only
    /// ever appear here when the real backend produced them — the service
    /// never invents them.
    public let messages: [SDKAssistMessage]
    /// Capability IDs the owning extension held ACTIVE grants for when the
    /// session was created (`SDKGrantStore`). `executeTool` only permits
    /// tools in this set — tool access per approved scope, enforced for
    /// real. Tools are addressed by capability ID; there is no separate
    /// tool-name registry to drift out of sync.
    public let allowedToolIDs: [String]

    public init(
        id: UUID = UUID(),
        extensionID: String,
        title: String?,
        systemPrompt: String? = nil,
        model: String? = nil,
        createdAt: Date = Date(),
        isClosed: Bool = false,
        messages: [SDKAssistMessage] = [],
        allowedToolIDs: [String] = []
    ) {
        self.id = id
        self.extensionID = extensionID
        self.title = title
        self.systemPrompt = systemPrompt
        self.model = model
        self.createdAt = createdAt
        self.isClosed = isClosed
        self.messages = messages
        self.allowedToolIDs = allowedToolIDs
    }
}

// MARK: - Response

/// The assistant's reply to one `send`. Produced ONLY by the real Assist
/// backend — never fabricated by the service.
public struct SDKAssistResponse: Sendable {
    public let sessionID: UUID
    public let text: String

    public init(sessionID: UUID, text: String) {
        self.sessionID = sessionID
        self.text = text
    }
}

// MARK: - Streaming

/// One event on a headless Assist response stream.
///
/// The stream shape is real: `.started` opens, `.delta` carries response
/// text chunks, then exactly one terminal event (`.completed` or
/// `.failed`). Until the backend boundary is wired (see
/// `SDKAssistService`), streams terminate with `.failed` — the service
/// never emits fabricated `.delta` text.
public enum SDKAssistStreamEvent: Sendable {
    case started(sessionID: UUID)
    case delta(String)
    case completed(SDKAssistResponse)
    case failed(SDKError)
}

// MARK: - Tool calls

/// One tool invocation requested through a headless Assist session.
public struct SDKAssistToolCall: Sendable {
    /// Addressed by capability ID and checked against the session's
    /// `allowedToolIDs` (the extension's approved scope, snapshotted at
    /// session creation).
    public let toolName: String
    /// String-valued arguments only, each bounded (see
    /// `SDKAssistService`); the host never forwards unbounded payloads.
    public let arguments: [String: String]

    public init(toolName: String, arguments: [String: String] = [:]) {
        self.toolName = toolName
        self.arguments = arguments
    }
}

/// The host's answer to one tool call. Produced ONLY by the real tool
/// runtime — never fabricated by the service.
public struct SDKAssistToolResult: Sendable {
    public let toolName: String
    /// True when the tool ran and returned normally.
    public let succeeded: Bool
    /// The tool's output text (bounded by the service).
    public let output: String

    public init(toolName: String, succeeded: Bool, output: String) {
        self.toolName = toolName
        self.succeeded = succeeded
        self.output = output
    }
}
