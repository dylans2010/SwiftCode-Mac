    }

    // MARK: - watchOS Code Generation

    private func generateWatchOSCode(scene: VisualUIScene) -> String {
        return """
//
//  VisualUIExportView.swift
//  Generated by SwiftCode WatchOS Template
//

import SwiftUI

struct WatchUIExportView: View {
    var body: some View {
        ScrollView {
            VStack(spacing: 12) {
                Image(systemName: "applewatch")
                    .font(.title)
                    .foregroundColor(.green)
                Text("watchOS Workspace")
                    .font(.headline)
            }
        }
    }
}
"""
    }

    // MARK: - Formatting Helpers

    private func indentLines(_ source: String, indentCount: Int) -> String {
        let indent = String(repeating: "    ", count: indentCount)
        let lines = source.components(separatedBy: "\n")
        return lines.map { $0.isEmpty ? "" : indent + $0 }.joined(separator: "\n")
    }
}
